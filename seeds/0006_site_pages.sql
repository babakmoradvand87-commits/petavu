/*
 * سه اصلاح که ساخت صفحه‌های گام ۲۵ نشان داد:
 *
 *   • `listing.default` عنوان «{title} | PETAVU» می‌ساخت. وقتی صفحه `title` نمی‌داد،
 *     نتیجه «| PETAVU» بود — یعنی عنوان **همهٔ صفحه‌های فهرست** (از جمله
 *     `/businesses`) تهی و فقط برند لاتین بود. حالا «{title} | {site}» است و
 *     توضیح، همان `{description}` صفحه (متنِ قبلی، «مشخصات، قیمت و راه تماس»،
 *     دربارهٔ آگهی کالا بود، نه فهرست کسب‌وکار).
 *   • `search.query` گیومه داشت. موتور قالب، تکه‌ها را با فاصله می‌چسباند و
 *     «جست‌وجوی «کلینیک»» به «جست‌وجوی « کلینیک »» تبدیل می‌شد.
 *   • قالب `content.page` نبود؛ صفحهٔ محتوای نوع `page` (مثل قوانین) به قالب
 *     عمومی تنظیمات می‌افتاد و برند دوبار می‌آمد («… | پِتاوو | PETAVU»).
 */
update seo.template
set title_template = '{title} {sep} {site}',
    description_template = '{description}'
where business_id is null and key = 'listing.default'
  and title_template = '{title} | PETAVU';

update seo.template
set title_template = 'جست‌وجو: {query} {sep} {site}',
    description_template = 'نتایج جست‌وجوی {query} در کسب‌وکارها و محتوای {site}.'
where business_id is null and key = 'search.query'
  and title_template like 'جست‌وجوی «%';

